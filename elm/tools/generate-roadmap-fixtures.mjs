#!/usr/bin/env node
// Generate the Elm literal fixture from the exact checked-in JSON catalog.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '../..');
const catalogPath = resolve(root, 'elm/fixtures/roadmap/catalog.json');
const outputPath = resolve(root, 'elm/tests/RoadmapFixtures.elm');
const raw = readFileSync(catalogPath, 'utf8');
JSON.parse(raw);
const sha256 = createHash('sha256').update(raw).digest('hex');
const elmString = value => [...value].map(char => {
  const point = char.codePointAt(0);
  if (char === '"') return '\\"';
  if (char === '\\') return '\\\\';
  if (char === '\n') return '\\n';
  if (char === '\r') return '\\r';
  if (char === '\t') return '\\t';
  if (point < 0x20 || point > 0x7e) return `\\u{${point.toString(16)}}`;
  return char;
}).join('');
const output = `module RoadmapFixtures exposing (catalogJson, catalogSha256)

{-| GENERATED by elm/tools/generate-roadmap-fixtures.mjs. Do not edit by hand.
Catalog SHA-256: ${sha256}
-}

catalogJson : String
catalogJson =
    "${elmString(raw)}"


catalogSha256 : String
catalogSha256 =
    "${sha256}"
`;
if (process.argv.includes('--check')) {
  const actual = readFileSync(outputPath, 'utf8');
  if (actual !== output) {
    process.stderr.write('RoadmapFixtures.elm is stale; run node elm/tools/generate-roadmap-fixtures.mjs\n');
    process.exit(1);
  }
} else {
  writeFileSync(outputPath, output);
}
